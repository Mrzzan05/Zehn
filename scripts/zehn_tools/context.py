from pathlib import Path


def read_file(path: Path) -> str:

    if not path.exists():
        return ""

    return path.read_text(
        encoding="utf-8"
    )


def section(
    title: str,
    content: str
) -> str:

    return f"""
# {title}

Source:

{content}

---

"""


def build_document(
    sections: list[tuple[str, str]]
) -> str:

    output = ""

    output += """
# Zehn Generated Context

This file is automatically generated.

Do not edit manually.

---

"""

    for title, content in sections:

        output += section(
            title,
            content
        )

    return output